-- 002_experiments.sql 对照实验：分组名单、阅读回执与隔离记录
CREATE TABLE IF NOT EXISTS experiments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_id integer REFERENCES segments(id),
    title character varying(100),
    note text,
    outreach_ids json,
    seed character varying(64),
    status character varying(20) DEFAULT 'running',
    result json,
    created character varying(40),
    updated character varying(40) DEFAULT '',
    archived character varying(40) DEFAULT ''
);
CREATE TABLE IF NOT EXISTS experiment_members (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id integer REFERENCES experiments(id),
    code character varying(60),
    cluster_id integer,
    arm character varying(10),
    CONSTRAINT experiment_members_experiment_id_code_key UNIQUE (experiment_id, code)
);
CREATE TABLE IF NOT EXISTS receipts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id integer REFERENCES experiments(id),
    event_id character varying(60),
    code character varying(60),
    created character varying(40),
    CONSTRAINT receipts_experiment_id_event_id_key UNIQUE (experiment_id, event_id)
);
CREATE TABLE IF NOT EXISTS quarantines (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id integer REFERENCES experiments(id),
    event_id character varying(60),
    code character varying(60),
    reason character varying(200),
    created character varying(40),
    CONSTRAINT quarantines_experiment_id_event_id_key UNIQUE (experiment_id, event_id)
);
